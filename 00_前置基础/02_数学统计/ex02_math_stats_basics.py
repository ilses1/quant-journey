fig, axes = plt.subplots(2, 3, figsize=(16, 10))

# axes 初始是 2×3 的二维数组 [[ax0, ax1, ax2], [ax3, ax4, ax5]]
# .flatten() 把它展平成一维数组 [ax0, ax1, ax2, ax3, ax4, ax5]
