# ============================================================
# 1. 准备数据：模拟三只股票的日收益率
# ============================================================

# 固定随机种子，让每次运行生成的"随机数"完全相同
# 这样调参或改策略时不会被随机波动干扰，能分辨是代码变了还是运气变了
np.random.seed(42)

# 模拟 500 个交易日（约 2 年的日线数据）
n = 500

# ------------------------------------------------------------------
# 1.1 用正态分布分别生成三只股票的"纯独立"收益率
# ------------------------------------------------------------------
# np.random.normal(loc, scale, size) 从正态分布中抽样
# 参数含义同 ex01：
#   loc   = 均值（中心位置），即日收益率的期望值
#   scale = 标准差（离散程度），即日波动率
#   size  = 样本数量

# stock_A: 日均收益 0.05%, 日波动率 1.5%  → 偏稳健型
stock_A = np.random.normal(0.0005, 0.015, n)

# stock_B: 日均收益 0.08%, 日波动率 2.2%  → 偏激进型（高收益高波动）
stock_B = np.random.normal(0.0008, 0.022, n)

# stock_C: 日均收益 0.02%, 日波动率 1.2%  → 偏保守型（低收益低波动）
stock_C = np.random.normal(0.0002, 0.012, n)

# ------------------------------------------------------------------
# 1.2 构造一个"市场因子"（模拟沪深300等大盘指数的收益率）
# ------------------------------------------------------------------
# market 是系统性风险来源，所有股票都或多或少受它影响
# 日均收益 0.04%, 日波动率 1.4%
market = np.random.normal(0.0004, 0.014, n)

# ------------------------------------------------------------------
# 1.3 将市场因子引入各股票，让它们拥有相关性
# ------------------------------------------------------------------
# 核心公式（单因子模型）：
#   stock_return = beta × market_return + epsilon
#
# 其中：
#   beta  = 个股对市场波动的敏感度
#           beta > 1 → 比市场波动更大（激进型，如科技股）
#           beta < 1 → 比市场波动更小（防御型，如公用事业股）
#   epsilon = 个股的独立成分（噪声项），和别的股票不相关，也和 market 不相关

# 人为设定三只股票的 Beta 值（真实场景下 Beta 是通过回归估计出来的）
beta_A, beta_B, beta_C = 0.8, 1.3, 0.5

# 重新计算各股票收益率：市场成分 + 独立噪声
# stock_A 的噪声标准差=0.008 → 纯独立波动很小，大部分波动来自市场
stock_A = beta_A * market + np.random.normal(0, 0.008, n)
#   结果 = 标量 × 数组 (逐个相乘) + 数组 (随机噪声)  (两个数组逐元素相加)
# stock_B 的噪声标准差=0.015 → 自身波动大，加上 beta=1.3，总波动最大
stock_B = beta_B * market + np.random.normal(0, 0.015, n)
# stock_C 的噪声标准差=0.006 → 波动最小，beta=0.5 也最低
stock_C = beta_C * market + np.random.normal(0, 0.006, n)

# 生成日期索引：从 2024-01-01 开始，生成 n 个工作日（freq="B"）
# "B" = Business day，自动跳过周六日和节假日
# periods=n 表示共生成 n 个日期，不是到某个截止日期为止
dates = pd.date_range("2024-01-01", periods=n, freq="B")

# 将四列收益率放入 DataFrame，索引设为日期
# Pandas 里 df.loc["2024-03"] 可以按日期切片，非常方便
df = pd.DataFrame({
    "stock_A": stock_A,  # A 股收益率序列
    "stock_B": stock_B,  # B 股收益率序列
    "stock_C": stock_C,  # C 股收益率序列
    "market":  market,   # 大盘收益率序列
}, index=dates)
# index	行标签，不传则自动 0,1,2...	index=dates

print("=== 0. 收益率数据预览（前5个交易日）===")
print(df.head())

# ============================================================
# 2. 统计基础：均值、标准差、偏度、峰度、相关系数
#    这些是描述任何收益率序列的"四维画像"
# ============================================================

print("\n=== 1. 统计基础 ===")

# 遍历 DataFrame 的每一列（四只"股票"分别分析）
for col in df.columns:
    # df[col].mean() — 计算该列所有值的算术平均
    # 对收益率而言，这就是"平均每天赚/亏多少"
    # 注意：.mean() 会自动跳过 NaN 值
    # 如果列里有 NaN 和有效值混合，.mean() 自动跳过 NaN：不计数
    # s = pd.Series([1.0, np.nan, 3.0])
    # print(s.mean())   # 2.0  (1+3)/2，跳过 NaN
    mu = df[col].mean()#收益率均值

    # df[col].std() — 计算该列的标准差
    # 标准差衡量数据在均值周围的离散程度
    # 对收益率而言，标准差 = 日波动率，越大说明涨跌越剧烈
    # Pandas .std() 默认用 ddof=1（样本标准差，分母 n-1）
    sigma = df[col].std()#标准差

    # 年化收益率：日收益率均值 × 252
    # 252 是 A 股一年的大致交易日数
    # 假设每天的收益率相互独立，年收益 = 每天收益的累加
    annual_return = mu * 252 #年化收益率

    # 年化波动率：日波动率 × √252
    # 为什么不是乘 252 而是乘 √252？
    # → 方差可累加：年方差 = 日方差 × 252
    # → 年标准差 = √(日方差 × 252) = 日标准差 × √252
    annual_vol = sigma * np.sqrt(252) #年化波动率  年标准差

    # 夏普比率 = (年化收益 - 无风险利率) / 年化波动率
    # 含义：每承担一单位风险，能获得多少超额回报
    # 无风险利率假设为 2%（约等于一年期国债收益率）
    # 夏普 > 1 良好，> 2 优秀，< 0 跑不过存银行
    sharpe = (annual_return - 0.02) / annual_vol #夏普比率  (年化收益率 - 无风险利率) / 年化波动率

    # ------------------------------------------------------------------
    # 偏度（Skewness）：衡量收益率分布的不对称性
    # ------------------------------------------------------------------
    # stats.skew() 计算偏度系数，值可正可负：
    #   偏度 > 0 → 右偏（正偏）：大部分日子小亏，偶尔大涨
    #              ┌──┐
    #            ┌─┤  ├─┐
    #          ┌─┤ │  │ ├───┐
    #   ──────┘  │ │  │ │   └─────────
    #            左         右（长尾在右边）
    #
    #   偏度 < 0 → 左偏（负偏）：大部分日子小赚，偶尔暴跌
    #                ┌──┐
    #          ┌───┐ │  │
    #   ──────┘   └─┤  ├─┐
    #               │  │ ├──────┐
    #   左（长尾在左边）        右
    #
    #   偏度 ≈ 0 → 对称分布（接近正态）
    #
    # 量化中的意义：
    #   负偏度（左偏）意味着暴跌的概率比正态分布高 → 风险大
    #   正偏度（右偏）意味着暴涨的概率比正态分布高 → "彩票"特性
    # SciPy 的 stats（统计）模块，包含大量统计检验和分布函数，这里只用到偏度和峰度
    s = stats.skew(df[col]) #偏度系数

    # ------------------------------------------------------------------
    # 峰度（Kurtosis）：衡量收益率分布的尾部厚度
    # ------------------------------------------------------------------
    # stats.kurtosis(data, fisher=False) 计算标准峰度
    #   标准峰度 ≈ 3 → 接近正态分布的尾部厚度
    #   标准峰度 > 3 → 厚尾（肥尾）
    #     含义：发生极端涨跌的概率比正态分布高得多
    #     现实中的股票收益率几乎都是厚尾分布
    #     （2008 年金融危机、2020 年新冠都是"正态分布无法解释的极端事件"）
    #   标准峰度 < 3 → 薄尾
    #     含义：极端值比正态分布少，分布更集中
    #
    # fisher=True（默认）返回"超额峰度"= 标准峰度 - 3
    # fisher=False 直接返回标准峰度（更直观）
    k = stats.kurtosis(df[col], fisher=False)

    # 格式化打印：`{col:>8s}` 右对齐宽度 8，`{x:7.4f}` 总宽 7 位保留 4 位小数
    # {col : > 8 s}
    #   │    │  │ │
    #   │    │  │ └── s = 字符串类型（string）
    #   │    │  └──── 8 = 总宽度为 8 个字符
    #   │    └─────── > = 内容靠右对齐
    #   └──────────── col 变量的值
    print(f"{col:>8s}: 年化收益={annual_return:7.4f}, 年化波动={annual_vol:6.4f}, "
          f"夏普={sharpe:6.4f}, 偏度={s:7.4f}, 峰度={k:7.4f}")

# ------------------------------------------------------------------
# 相关系数矩阵（Correlation Matrix）
# ------------------------------------------------------------------
# df.corr() 计算任意两列之间的皮尔逊相关系数（Pearson r）
# 相关系数 ∈ [-1, 1]：
#   +1   → 完全正相关（你涨我必涨）
#    0   → 不相关（你我涨跌独立）
#   -1   → 完全负相关（你涨我必跌）
#
# 量化中的意义：
#   组合里买两只相关系数接近 1 的股票 = 分散了个寂寞（三桶油、四大行之间的关系）
#   组合里买两只相关系数为负的股票 = 真正的风险分散
#   多因子模型中用相关系数判断因子之间的共线性
print("\n--- 相关系数矩阵 ---")
print(df.corr().round(4))  # .round(4) 保留 4 位小数，矩阵太大不便细看

# ============================================================
# 3. 正态性检验（Jarque-Bera 检验）
#    核心问题：日收益率真的服从正态分布吗？
# ============================================================

print("\n=== 2. 正态性检验（Jarque-Bera）===")

# Jarque-Bera 检验利用偏度和峰度来判断数据是否偏离正态分布
#
# JB 统计量的构造逻辑：
#   如果数据是真的正态分布 → 偏度 ≈ 0、峰度 ≈ 3 → JB 统计量很小
#   如果数据偏离正态       → 偏度或峰度不正常 → JB 统计量很大
#
# 假设检验框架：
#   H0（原假设）：数据服从正态分布
#   H1（备择假设）：数据不服从正态分布
#   p-value（p 值）：在原假设成立的前提下，观察到当前统计量的概率
#     p < 0.05 → 拒绝 H0 → 数据不服从正态分布
#     p > 0.05 → 不能拒绝 H0 → 可能是正态分布
#
# 量化里的残酷事实：
#   实盘收益率几乎从不服从正态分布
#   原因：市场有涨跌停限制、流动性枯竭、恐慌性抛售、政策干预
#   把收益率当正态分布去算 VaR（风险价值）会严重低估极端风险

for col in df.columns:
    # stats.jarque_bera(data) 返回两个值：
    #   jb_stat   = JB 统计量（越大越偏离正态）
    #   jb_pvalue = p 值（越小越"有把握说不是正态"）
    jb_stat, jb_pvalue = stats.jarque_bera(df[col])

    # Python 的三元表达式，等价于：
    # if jb_pvalue < 0.05:
    #     result = "拒绝正态"
    # else:
    #     result = "可能正态"
    # 一行写法就是：值A if 条件 else 值B —— 条件成立取 A，不成立取 B。

    #     # 判断结果：p < 0.05 则拒绝正态假设
    result = "拒绝正态" if jb_pvalue < 0.05 else "可能正态"
    print(f"{col:>8s}: JB统计量={jb_stat:8.4f}, p值={jb_pvalue:8.4f} → {result}")

# ============================================================
# 4. 线性回归（OLS）：用市场收益率解释个股收益率 → 计算 Beta
# ============================================================

# 为什么需要回归？
#   量化交易不关心"这只股票涨了多少"
#   量化关心的是"这只股票的涨跌有多少是市场驱动、有多少是自身驱动"
#   市场驱动的部分谁都能拿到（买 ETF 就行）
#   自身驱动的部分才是选股能力（超额收益 alpha 的来源）
#
# 回归方程：
#   stock_return(t) = α + β × market_return(t) + ε(t)
#
#   因变量 y：stock_return — 我们想解释的变量（个股收益率）
#   自变量 X：market_return — 用来解释的变量（市场收益率）
#   参数 α（alpha/截距）：当市场不涨不跌时，个股本身的平均收益
#          α > 0 且显著 → 这只股票有独立于市场的超额收益（好！）
#          α ≈ 0        → 涨跌全看大盘脸色
#   参数 β（Beta/斜率）：市场涨 1%，个股预期涨 β%
#          β = 1       → 和市场同步（买 ETF 的效果）
#          β > 1       → 比市场波动大（杠杆效应，牛市跑赢、熊市更惨）
#          β < 1       → 比市场波动小（防御型）
#   误差 ε：回归方程解释不了的部分（个股的独立波动）

print("\n=== 3. 线性回归：计算 Beta ===")

for stock_name in ["stock_A", "stock_B", "stock_C"]:
    # ------------------------------------------------------------------
    # 准备自变量 X 和因变量 y
    # ------------------------------------------------------------------
    X = df["market"]    # 自变量：大盘收益率（一维 Series）
    y = df[stock_name]  # 因变量：个股收益率（一维 Series）

    # sm.add_constant(X) 在 X 前面加一列全为 1 的"截距列"
    # 为什么要加？
    #   如果不加，回归方程是 y = β × X（强制通过原点）
    #   加了之后，回归方程是 y = α + β × X（允许截距 α 不为零）
    #   我们想要 α，所以必须加
    #   add_constant 返回一个 DataFrame，第一列叫 "const"（全为1），第二列是原数据
    X = sm.add_constant(X) #sm 是 statsmodels：计量经济学建模库

    # sm.OLS(y, X) 创建一个 OLS（普通最小二乘法）模型对象
    #   y：因变量
    #   X：自变量（包含 const 列）
    # .fit() 执行拟合：在所有可能的 α 和 β 中，找到让"误差平方和最小"的那组
    #   返回一个 RegressionResults 对象，包含所有回归诊断信息

    
    model = sm.OLS(y, X).fit()
    # 拟合就是用一个简单的数学公式去"逼近"一堆散乱的数据点。
    # 找一条直线 个股 = α + β × 大盘 来描述这两者的关系——这条直线就是你的"拟合结果"。
    # 最小二乘法就是找这条直线的具体方法。
    # 核心思想：每条候选直线都会在 500 个点上产生 500 个误差（实际值 - 直线预测值）。把这些误差平方后加起来，和最小的那条直线就是最优解。
    # 一句话总结: 拟合 = 找规律，最小二乘法 = 怎么找。

    # model.params 是一个 Series，index 是变量名（"const" 和 "market"）
    # params["const"] = α（截距），params["market"] = β（斜率/Beta）
    alpha = model.params["const"]     # 截距 α：市场不动时个股的平均收益
    beta  = model.params["market"]    # 斜率 β：个股对市场的敏感度

    # model.rsquared = R²（决定系数），范围 [0, 1]
    # R² 的含义：市场涨跌能解释这支股票波动的大约百分之多少
    #   R² = 0.8  → 80% 的波动来自市场，20% 来自个股自身
    #   R² = 0.2  → 市场不太能解释这只股票，它有自己独立的驱动因素
    r_sq = model.rsquared

    # {alpha:+.6f} 中 + 号让正数也显示 + 号（-0.000050 vs +0.000327）
    print(f"{stock_name}: alpha={alpha:+.6f}, beta={beta:.4f}, R2={r_sq:.4f}")

# 预期结果：
#   我们设定的 beta_A=0.8, beta_B=1.3, beta_C=0.5
#   回归估计出来的 beta 应该接近这些值（因为模拟数据时故意这么造的）
#   实际值可能稍有偏差（随机噪声的影响），但大致在设定值附近

# ============================================================
# 5. 协方差矩阵（组合优化的基础）
# ============================================================

# 协方差衡量的是"两个变量一起变动的方向和幅度"
#   协方差 > 0 → 同涨同跌（正相关）
#   协方差 < 0 → 一个涨另一个跌（负相关）
#   协方差 ≈ 0 → 没啥关系
#
# 方差是协方差的特例：一个变量和自己的协方差 = 方差
#   协方差矩阵的对角线 = 各资产的方差
#   非对角线 = 两两之间的协方差

print("\n=== 4. 协方差矩阵（年化）===")

# df.cov() 计算日收益率的协方差矩阵
# 乘以 252 得到年化协方差（方差可线性累加：年方差 = 日方差 × 252）
cov_annual = df.cov() * 252
print(cov_annual.round(4))

# 这个矩阵在量化中的用途：
#   马克维茨均值-方差优化（找最优权重配比）
#   风险平价（让每个持仓贡献相等的风险）
#   计算组合的总体波动率  σ_portfolio = √(w^T × Σ × w)
#      w = 权重向量，Σ = 协方差矩阵

# ============================================================
# 6. 假设检验：t 检验
#    核心问题：这只股票的日均收益是"真的能赚钱"还是"纯碰运气"？
# ============================================================

print("\n=== 5. t 检验：日均收益是否显著 != 0 ===")

# 单样本 t 检验（stats.ttest_1samp）用于检验"数据的均值是否等于某个指定值"
#
# 假设检验框架（再次复习）：
#   H0（原假设）：日均收益 = 0（策略不赚钱，纯粹运气）
#   H1（备择假设）：日均收益 != 0（策略真能赚钱）
#   p-value < 0.05 → 拒绝 H0 → 收益统计显著
#   p-value > 0.05 → 不能拒绝 H0 → 可能只是运气
#
# t 统计量的构造直觉：
#   t = (样本均值 - 0) / (样本标准差 / √样本量)
#   t 越大 → 均值相对于波动来说"越突出" → 越不像是运气
#   样本量越大、波动越小 → t 越大 → 越容易显著

for col in df.columns:
    # stats.ttest_1samp(data, popmean) 对 data 做单样本 t 检验
    #   data：要检验的样本数据
    #   popmean：H0 中声称的总体均值（这里填 0，即检验"均值是否不为零"）
    # 返回值：
    #   t_stat  = t 统计量（越大越显著）
    #   p_value = p 值（越小越显著，< 0.05 才敢说"不是零"）
    t_stat, p_value = stats.ttest_1samp(df[col], 0)

    result = "显著 != 0" if p_value < 0.05 else "不显著"
    print(f"{col:>8s}: t统计量={t_stat:8.4f}, p值={p_value:.6f} → {result}")

# 量化中的关键认知：
#   做多因子选股时，每个因子都要过 t 检验
#   IC（信息系数）序列的 t 检验 → 判断因子是否真的有选股能力
#   策略回测收益的 t 检验 → 判断策略年化收益是否统计显著
#   如果 p > 0.05，年化 30% 也可能是运气好——样本外大概率亏回去

# ============================================================
# 7. 价格生成 + ADF 平稳性检验
#    核心问题：这个序列"能预测"吗？
# ============================================================

# 从日收益率反向构造价格序列（模拟随机游走）
# 价格 = 初始价格 × (1+r₁) × (1+r₂) × ... × (1+rₙ)
# np.cumprod = 累积乘积，和 ex01 里完全一样的逻辑
# .values 把 Pandas Series 转为 NumPy 数组
price_A = 10 * np.cumprod(1 + df["stock_A"].values)
price_B = 10 * np.cumprod(1 + df["stock_B"].values)

# 价差 = 两只股票价格的差
# 配对交易的核心思想：
#   如果两只股票的基本面相似（如工行和建行），它们的价差应该"均值回归"
#   价差偏离均值过大 → 做多便宜的、做空贵的 → 等价差回归后平仓
spread = price_A - price_B

print("\n=== 6. ADF 平稳性检验 ===")

# ADF（Augmented Dickey-Fuller）检验：判断序列是否平稳
#
# 通俗理解"平稳"和"非平稳"：
#   平稳序列：统计性质（均值、方差、自相关）不随时间变化
#     例子：日收益率（涨涨跌跌围绕 0 附近，不会越来越极端）
#     可预测性：可以做均值回归策略
#
#   非平稳序列：统计性质随时间变化
#     例子：股价本身（长期从 10 块涨到 100 块，均值一直在变）
#     可预测性：不能直接做均值回归
#
# ADF 检验的假设框架：
#   H0（原假设）：序列有单位根 = 非平稳
#   H1（备择假设）：序列平稳
#   p < 0.05 → 拒绝 H0 → 序列平稳（可预测）
#   p > 0.05 → 不能拒绝 H0 → 序列非平稳（不可直接用均值回归）

# 检验三种序列：价格（应非平稳）、收益率（应平稳）、价差（看情况）
for name, series in [("price_A(价格)", price_A),
                     ("stock_A(收益率)", df["stock_A"]),
                     ("spread(价差)", spread)]:
    # sm.tsa.adfuller(series, autolag="AIC") 执行 ADF 检验
    #   series：要检验的时间序列
    #   autolag="AIC"：自动选择最优滞后阶数（用 AIC 信息准则）
    # 返回值是一个元组：
    #   [0] adf_statistic    = ADF 检验统计量（越负越倾向平稳）
    #   [1] pvalue           = p 值（<0.05 则平稳）
    #   [2] usedlag          = 使用的滞后阶数
    #   [3] nobs             = 有效样本量
    #   [4] critical_values  = 1%, 5%, 10% 临界值字典
    #   [5] icbest           = 最优信息准则值
    # 用 _ 跳过不需要的返回值（usedlag, nobs, icbest）
    adf_stat, adf_pvalue, _, _, critical_values, _ = sm.tsa.adfuller(series, autolag="AIC")

    # 判断结果
    is_stationary = "平稳" if adf_pvalue < 0.05 else "非平稳"
    print(f"{name}: ADF={adf_stat:8.4f}, p值={adf_pvalue:.6f} → {is_stationary}")

# 预期结果：
#   price_A：非平稳（价格是随机游走，均值一直在漂移）
#   stock_A（收益率）：平稳（收益率总是在一个均值附近波动）
#   spread：可能平稳也可能非平稳（取决于两只股票是否真的"绑在一起"）

# ============================================================
# 8. 自相关分析（ACF）→ 趋势信号 vs 反转信号的依据
# ============================================================

print("\n=== 7. 自相关（ACF）===")

# 自相关（Autocorrelation）：序列当前值和自己过去值的相关性
#
# 用收益率举例：
#   lag=1 的 ACF：今天的收益率和昨天的收益率有关系吗？
#   lag=5 的 ACF：今天的收益率和 5 天前的收益率有关系吗？
#
# ACF 值 ∈ [-1, 1]：
#   ACF > 0  → 正自相关 → 涨了还会涨、跌了还会跌（动量效应）
#              → 策略方向：追涨杀跌（趋势跟踪）
#   ACF < 0  → 负自相关 → 涨了会回落、跌了会反弹（反转效应/均值回归）
#              → 策略方向：低买高卖（反转策略）
#   ACF ≈ 0 → 无自相关 → 过去的价格对未来没有预测力（弱有效市场）
#              → 策略方向：别白费力气预测收益率了，换个思路
#
# 量化中的实际应用：
#   如果 ACF(1) 显著为负 → 做短期反转策略（隔夜反转、日内反转）
#   如果 ACF(20) 显著为正 → 做中长期动量策略

for col in ["stock_A", "stock_B"]:
    # sm.tsa.acf(data, nlags=5) 计算前 5 阶自相关系数
    #   data：收益率序列
    #   nlags=5：计算 lag 1 到 lag 5（即滞后 1~5 天的自相关）
    # 返回值：[lag0, lag1, lag2, lag3, lag4, lag5] 共 6 个值
    #   lag0 永远 = 1（序列和自己的相关性必然是 1，没意义）
    # tsa = Time Series Analysis（时间序列分析），statsmodels 的子模块。专门放时间序列相关的函数。
    acf_values = sm.tsa.acf(df[col], nlags=5)

    print(f"\n{col} 自相关:")
    #range 只是"范围描述"（三个数：0, 5, 1），不占内存空间，只是在循环中用到
    # range(start, stop, step)：每 step 个取一个
    # list(range(0, 10, 2))  # [0, 2, 4, 6, 8]   正步长

    for lag in range(1, 6):  # lag 从 1 到 5
        direction = ""
        if acf_values[lag] > 0.1:
            direction = " → 正相关(动量倾向)"
        elif acf_values[lag] < -0.1:
            direction = " → 负相关(反转倾向)"
        # 在 -0.1 到 +0.1 之间 → 无明显自相关，不标注
        print(f"  lag={lag}: ACF={acf_values[lag]:+.4f}{direction}")

# 本模拟数据是纯随机生成的，而且加入了市场因子影响
# 所以自相关应该都接近 0（无显著动量或反转效应）
# 在真实数据上，你可能会发现 A 股有短期反转效应（跌多了反弹）

