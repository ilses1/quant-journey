axes = axes.flatten()

# --- 前 4 个子图：收益率分布直方图 ---
# enumerate(df.columns) 同时返回索引号和列名 给每个元素自动编号，返回 (序号, 值) 对：
for i, col in enumerate(df.columns):
    ax = axes[i]         # 当前子图对象
    data = df[col]      # 当前列的收益率数据

    # ax.hist() 画直方图（频数分布图）
    #   bins=40：分成 40 个柱子
    #   density=True：归一化为概率密度（整个直方图面积为 1）
    #                 如果不设，Y 轴是"出现次数"，不同数据集没法对比
    #   alpha=0.6：柱子半透明（60% 不透明度）
    #   color="orange"：橙色的柱子
    #   edgecolor="white"：柱子之间用白线隔开，视觉更清晰
    ax.hist(data, bins=40, density=True, alpha=0.6, color="orange", edgecolor="white")

    # 叠加一个理论正态分布曲线（PDF，概率密度函数）
    # np.linspace(a, b, num) 在 [a, b] 之间等距生成 num 个点
    # 用数据的实际最小值和最大值作为 X 轴范围
    x = np.linspace(data.min(), data.max(), 200)

    # stats.norm.pdf(x, loc, scale) 计算正态分布在 x 各点的概率密度值
    #   loc   = 均值（曲线的中心位置）
    #   scale = 标准差（曲线的宽窄程度）
    # "b-" = 蓝色实线，linewidth=2 线宽 2 像素
    ax.plot(x, stats.norm.pdf(x, data.mean(), data.std()),
            "b-", linewidth=2, label="Normal fit")

    ax.set_title(col)
    # ax.axvline(x=0) 在 X=0 处画一条垂直线
    #   灰色（gray）、虚线（linestyle="--"）、半透明（linewidth=0.8）
    #   作用是标注"零收益率线"，一眼看出涨跌各占多少
    ax.axvline(0, color="gray", linestyle="--", linewidth=0.8)
    ax.legend(fontsize=8)

